import { describe, it, expect } from 'vitest';
import { decodeCps2Key20, cps2Decrypt } from '../capcom/decrypt.js';

// The real ddtod.key ROM region (20 bytes, 40 hex chars), from
// data/ddtod/cps2/ddtod.zip (CRC32 41dfca41, per MAME's own
// ROM_START(ddtod) -- see docs/ddtod/cps2/data-structure.md). This is a
// second, independent CPS2 title/key -- verifies decodeCps2Key20()/
// cps2Decrypt() generalize past ddsom's own key.
const DDTOD_KEY_BYTES = Buffer.from('07000240000878c26020000a6eb14ca041ff9b88', 'hex');

describe('decodeCps2Key20 (ddtod)', () => {
  it("decodes ddtod.key to the known master key + watchdog (cross-checked against historic-mame's hardcoded per-game key table)", () => {
    const info = decodeCps2Key20(DDTOD_KEY_BYTES);
    // Matches historic-mame's cps2crpt.c entry exactly:
    // { "ddtod", { 0x4767fe08,0x14ca35d9 }, 0x180000 }, // 0C78 1019 4000 cmpi.w #$1019,$4000
    expect(info.masterKey[0] >>> 0).toBe(0x4767fe08);
    expect(info.masterKey[1] >>> 0).toBe(0x14ca35d9);
    expect(info.watchdogInstructionWords).toEqual([0x0c78, 0x1019, 0x4000]);
    // NOTE: `upper` (0x200000) intentionally does NOT match historic-mame's
    // hardcoded 0x180000 here -- see docs/ddtod/cps2/data-structure.md
    // § "2.2 Key file format" for why the modern per-key-byte formula
    // (which this decoder implements, ported from current mamedev/mame's
    // own init_cps2crypt()) is trusted over that older, hand-tuned table
    // entry. The disassembly-based ground truth (60+ coherent instructions
    // at the decrypted reset vector, including the exact watchdog opcode
    // above) confirms 0x200000 is the value real hardware actually uses.
    expect(info.lower).toBe(0);
    expect(info.upper).toBe(0x200000);
  });
});

describe('cps2Decrypt (ddtod)', () => {
  it("produces a plausible 68000 reset vector for ddtod's real program ROM", () => {
    // See tools/shared/cps2/__tests__/decrypt.test.ts (ddsom) for why this
    // is a structural/determinism regression test, not a re-read of the
    // real (uncommitted) ROM -- the actual reset-vector ground truth
    // (SP=0x00ff0e6a, PC=0x0000089a, 60+ coherent disassembled
    // instructions including the watchdog opcode) is recorded in
    // docs/ddtod/cps2/data-structure.md and data/extracted/ddtod/
    // decrypt-info.json (regenerated by `npx tsx tools/ddtod/
    // export-game-data.ts data/ddtod/cps2`).
    const info = decodeCps2Key20(DDTOD_KEY_BYTES);
    const rom = new Uint8Array(0x10000);
    for (let i = 0; i < rom.length; i++) rom[i] = (i * 37 + 11) & 0xff;

    const dec1 = cps2Decrypt(rom, info.masterKey, info.upper);
    const dec2 = cps2Decrypt(rom, info.masterKey, info.upper);
    expect(dec1.length).toBe(rom.length);
    expect(dec1).toEqual(dec2); // deterministic
    expect(dec1).not.toEqual(rom); // actually transforms the input
  });
});
