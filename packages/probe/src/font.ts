/** Unknown characters render as this so a bad caption is visible, not invisible. */
const FALLBACK = GLYPHS['?'];

/** Glyph rows for one character (input is upcased; unknown chars get '?'). */
export function glyphFor(ch: string): string[] {
  return GLYPHS[ch.toUpperCase()] ?? FALLBACK;
}

/** Pixel width of a rendered string (glyphs + 1px spacing). */
export function textWidth(text: string, scale = 1): number {
  return text.length * (GLYPH_WIDTH + 1) * scale;
}
